let currentLocale = 'en';

export function resolveDepositLocale(countryCode) {
  if (!countryCode) return 'en';
  return COUNTRY_LOCALE[countryCode.trim().toUpperCase()] || 'en';
}

export function t(key, params = {}) {
  const table = STRINGS[currentLocale] || STRINGS.en;
  const raw = table[key] ?? STRINGS.en[key] ?? key;
  return raw.replace(/\{(\w+)\}/g, (_, k) => (params[k] != null ? String(params[k]) : ''));
}

export function getTdsStages() {
  return [
    { pct: 0, text: t('tdsStage0') },
    { pct: 15, text: t('tdsStage15') },
    { pct: 40, text: t('tdsStage40') },
    { pct: 65, text: t('tdsStage65') },
    { pct: 85, text: t('tdsStage85') },
    { pct: 100, text: t('tdsStage100') },
  ];
}

export function applyDepositLocale(countryCode) {
  currentLocale = resolveDepositLocale(countryCode);
  const lang = HTML_LANG[currentLocale] || 'en';
  document.documentElement.lang = lang;
  document.title = t('pageTitle');

  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (key) el.textContent = t(key);
  });

  const bankTop = document.getElementById('bankCarouselTop');
  const bankBottom = document.getElementById('bankCarouselBottom');
  const aria = t('bankLogosAria');
  if (bankTop) bankTop.setAttribute('aria-label', aria);
  if (bankBottom) bankBottom.setAttribute('aria-label', aria);

  const tdsOverlay = document.getElementById('tdsOverlay');
  if (tdsOverlay) tdsOverlay.setAttribute('aria-label', t('tdsAria'));

  const successOverlay = document.getElementById('successOverlay');
  if (successOverlay) successOverlay.setAttribute('aria-label', t('successAria'));

  const tdsStatus = document.querySelector('#tdsStatusText span');
  if (tdsStatus && !tdsStatus.closest('#tdsStatusText')?.dataset.busy) {
    tdsStatus.textContent = t('tdsStatusInitial');
  }
}

export function getDepositLocale() {
  return currentLocale;
}
